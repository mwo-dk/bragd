// Turns the verbatim upstream piece artwork into the form the sprite build can
// theme, changing nothing that is drawn.
//
// **Why this step exists at all.** `tools/pieces/build-pieces.mjs` recolours a piece by
// replacing the two colour literals with CSS custom properties, which is a blind
// text substitution over the markup. That is only safe if the artwork spells its
// colours in exactly one way, and the upstream files do not: they mix `#000000`
// with `#000` and `#ffffff` with `#fff`, in `style` strings and in attributes.
//
// The failure that makes this a build step rather than a note is specific and
// silent. The substitution matches `#000`, which is a *prefix* of `#000000`, so
// an unnormalised file becomes `var(--piece-black-fill, #000)000` — markup that
// still parses, still renders, and is wrong. Normalising the widths first makes
// that impossible rather than tested-for.
//
// **What this does not touch: `d` attributes.** Not one number of the drawing
// changes, and `--verify` re-reads both directories afterwards and asserts it.
// The point of keeping `assets/pieces/upstream/` verbatim beside the output is
// that the modification the BSD licence asks us to state is a diff anyone can
// run, rather than a paragraph anyone has to believe.
//
// Run: node tools/pieces/normalise-upstream-pieces.mjs [--verify]

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const source = join(root, "assets", "pieces", "upstream");
const output = join(root, "assets", "pieces", "basic");

// Upstream's own names: piece letter, then l/d for which side, then t for a
// transparent background.
const PIECES = {
  klt: "king-w",
  kdt: "king-b",
  qlt: "queen-w",
  qdt: "queen-b",
  rlt: "rook-w",
  rdt: "rook-b",
  blt: "bishop-w",
  bdt: "bishop-b",
  nlt: "knight-w",
  ndt: "knight-b",
  plt: "pawn-w",
  pdt: "pawn-b",
};

/** Every `d="…"` in a file, whitespace-flattened, in document order. */
function geometry(markup) {
  return (markup.replace(/\s+/g, " ").match(/ d="[^"]*"/g) ?? []).map((d) =>
    d.replace(/\s+/g, " ").trim(),
  );
}

/**
 * The whole modification: six-digit colours become three-digit, and the two
 * literals are spelled in one case.
 *
 * Deliberately not a general colour parser. These twelve files contain exactly
 * four distinct literals — asserted below — and anything else is a file we have
 * not looked at, which should stop the build rather than be guessed at.
 */
function normaliseColours(markup, name) {
  const seen = new Set(markup.match(/#[0-9a-fA-F]{3,6}/g) ?? []);
  for (const literal of seen) {
    if (!/^#(fff|000|ffffff|000000)$/i.test(literal)) {
      throw new Error(`${name}: unexpected colour ${literal}`);
    }
  }
  return markup
    .replace(/#ffffff/gi, "#FFF")
    .replace(/#000000/gi, "#000")
    .replace(/#fff\b/gi, "#FFF");
}

const HEADER = (name, upstream) => `<?xml version="1.0" encoding="UTF-8"?>
<!--
	${name}

	Original: Chess_${upstream}45.svg by Cburnett, from Wikimedia Commons
	https://commons.wikimedia.org/wiki/File:Chess_${upstream}45.svg

	Multi-licensed by its author under GFDL 1.2+, CC BY-SA 3.0, GPL v2+ and the
	3-clause BSD licence. **We take the 3-clause BSD licence**, which is why
	work derived from this set carries no share-alike obligation. See
	assets/pieces/LICENCE.md.

	GENERATED by tools/pieces/normalise-upstream-pieces.mjs from the verbatim copy in
	assets/pieces/upstream/. The only modification is colour spelling —
	six-digit hex written as three-digit, in one case — so that the sprite build
	can substitute CSS custom properties without corrupting a literal. No path
	data is altered; the tool's verify mode proves it.
-->
`;

let checked = 0;
const verifyOnly = process.argv.includes("--verify");
mkdirSync(output, { recursive: true });

for (const [upstream, name] of Object.entries(PIECES)) {
  const original = readFileSync(join(source, `${upstream}.svg`), "utf8");

  // Everything inside the root element, so the header and any DOCTYPE go.
  const inner = original.match(/<svg\b[^>]*>([\s\S]*)<\/svg>/);
  if (!inner) throw new Error(`${upstream}: no <svg> element`);

  const body = normaliseColours(inner[1], upstream).replace(/\s*id="path\d+"/g, "");
  const svg =
    HEADER(name, upstream) +
    `<svg xmlns="http://www.w3.org/2000/svg" width="45" height="45" viewBox="0 0 45 45">` +
    `${body.trimEnd()}\n</svg>\n`;

  if (!verifyOnly) writeFileSync(join(output, `${name}.svg`), svg);

  // The assertion the licence note leans on.
  const before = geometry(original);
  const after = geometry(readFileSync(join(output, `${name}.svg`), "utf8"));
  if (before.length !== after.length || before.some((d, i) => d !== after[i])) {
    throw new Error(
      `${name}: path data changed — ${before.length} paths upstream, ${after.length} after`,
    );
  }
  checked += before.length;
}

console.log(
  `${verifyOnly ? "verified" : "normalised"} ${Object.keys(PIECES).length} pieces, ` +
    `${checked} paths identical to upstream`,
);
