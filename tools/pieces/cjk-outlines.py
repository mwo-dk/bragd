#!/usr/bin/env python3
"""Builds the xiangqi and janggi sprites with every character drawn as an outline.

    python3 tools/pieces/cjk-outlines.py NotoSansTC-Bold.otf NotoSansKR-Bold.otf

The sources are assets/pieces/xiangqi/xiangqi-pieces.svg and
assets/pieces/janggi/janggi-pieces.svg, which set each character as `<text>`.
This replaces every `<text>` with the glyph's outline, centred on the point the
text was anchored at, and writes gui/src/lib/sprites/. No piece then depends on
an installed font.

Xiangqi takes Noto Sans CJK TC Bold (its pieces are traditional characters) and
janggi Noto Sans CJK KR Bold (hanja as Korean sets print them). Both come from
the Sans2.004 release of notofonts/noto-cjk (17_NotoSansKR.zip, 19_NotoSansTC.zip)
and are SIL Open Font License 1.1. The fonts are not kept in the repository;
the outlines are, with the notice in each sprite and the licence in
assets/pieces/OFL-NotoSansCJK.txt.

Needs fontTools (`pip install fonttools`).
"""

import pathlib
import re
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
SHEETS = ("xiangqi", "janggi")  # in the order of the font arguments
# Presentation attributes that only meant something to `<text>`.
TEXT_ONLY = re.compile(r'\s(font-size|font-weight|font-family|text-anchor|dominant-baseline)="[^"]*"')

NOTICE = """	<!--
		GENERATED by tools/pieces/cjk-outlines.py from
		assets/pieces/{name}/{name}-pieces.svg — do not edit by hand. The source
		says why the pieces look as they do.

		The characters are glyph outlines from {font} (Noto Sans CJK),
		{copyright}
		Used under the SIL Open Font License 1.1. This file holds outlines, not
		the font. The licence is in assets/pieces/OFL-NotoSansCJK.txt.
	-->
"""


def attr(tag: str, name: str) -> str | None:
    found = re.search(rf'\s{name}="([^"]*)"', tag)
    return found[1] if found else None


def outline(font: TTFont, character: str, size: float, x: float, y: float, fill: str | None) -> str:
    """One character as a path whose glyph box is centred on (x, y)."""
    name = font.getBestCmap().get(ord(character))
    if name is None:
        sys.exit(f"{character!r} is not in {font['name'].getDebugName(4)}")
    glyphs = font.getGlyphSet()
    pen, box = SVGPathPen(glyphs), BoundsPen(glyphs)
    glyphs[name].draw(pen)
    glyphs[name].draw(box)
    x0, y0, x1, y1 = box.bounds
    s = size / font["head"].unitsPerEm
    # A font's y runs up and SVG's down, hence the negative scale.
    tx, ty = x - (x0 + x1) / 2 * s, y + (y0 + y1) / 2 * s
    paint = f' fill="{fill}"' if fill else ""
    return f'<path transform="translate({tx:.3f} {ty:.3f}) scale({s:.5f} {-s:.5f})"{paint} d="{pen.getCommands()}"/>'


def convert(source: str, font: TTFont, name: str) -> str:
    def symbol(m: re.Match) -> str:
        tag, inner = m[1], m[2]

        def text(t: re.Match) -> str:
            size = attr(t[1], "font-size") or attr(tag, "font-size")
            if size is None:
                sys.exit(f"{name}: a <text> with no font-size in {attr(tag, 'id')}")
            return outline(font, t[2], float(size), float(attr(t[1], "x")), float(attr(t[1], "y")), attr(t[1], "fill"))

        inner, count = re.subn(r"<text(\s[^>]*)>(.)</text>", text, inner)
        assert count == 1, f"{name}: {attr(tag, 'id')} has {count} characters"
        return TEXT_ONLY.sub("", tag) + inner + "</symbol>"

    body = source[source.index("-->") + 3 :]  # drop the source's header
    body = re.sub(r"(<symbol\b[^>]*>)(.*?)</symbol>", symbol, body, flags=re.S)
    assert "<text" not in body, f"{name}: a <text> outside a symbol"
    n = font["name"]
    notice = NOTICE.format(name=name, font=n.getDebugName(4), copyright=n.getDebugName(0))
    return source[: source.index("<!--")] + notice.lstrip("\t") + "\n\t" + body.lstrip()


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    for name, path in zip(SHEETS, sys.argv[1:]):
        font = TTFont(path)
        source = (ROOT / "assets" / "pieces" / name / f"{name}-pieces.svg").read_text()
        out = ROOT / "gui" / "src" / "lib" / "sprites" / f"{name}-pieces.svg"
        out.write_text(convert(source, font, name))
        print(f"wrote {out.relative_to(ROOT)} from {font['name'].getDebugName(4)}")


if __name__ == "__main__":
    main()
