#!/usr/bin/env python3
"""Builds the brand art: the rune wordmark, the icon, the splash, their PNGs
and the Tauri icon set.

    python3 tools/brand/build-brand.py

Every letter is a glyph outline from assets/fonts/NotoSansRunic-Regular.ttf
(SIL Open Font License 1.1), which has the runes and the Latin letters both, so
no picture depends on an installed font. Needs fontTools, Pillow and
rsvg-convert (librsvg).

Writes assets/brand/*.svg, assets/brand/png/<name>-<size>.png and, from the
icon, assets/brand/icons/.
"""

import io
import pathlib
import shutil
import subprocess

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
BRAND = ROOT / "assets" / "brand"
FONT = TTFont(ROOT / "assets" / "fonts" / "NotoSansRunic-Regular.ttf")
GLYPHS, CMAP, UPM = FONT.getGlyphSet(), FONT.getBestCmap(), FONT["head"].unitsPerEm

# The brand ramp (docs/spec.md) and the Board theme's gold.
DEEPEST, RACING, MID, LIGHT, PALE = "#00301b", "#004225", "#0b5c39", "#4f9d76", "#e9f0ea"
GOLD = "#d8b74a"
RUNES = "ᛒᚱᛅᚴᚦ"
APP_ICON = "icon"

NOTICE = (
    "<!-- Bragd brand art, generated by tools/brand/build-brand.py; do not edit by hand. "
    "Letters are outlines from Noto Sans Runic, Copyright 2022 The Noto Project Authors, "
    "SIL Open Font License 1.1 (assets/fonts/OFL.txt). -->"
)


def line(text: str, size: float, x: float, baseline: float, fill: str, anchor: str = "middle",
         tracking: float = 0.0, bold: float = 0.0) -> str:
    """A line of text as outlines. `bold` thickens the strokes by that many font units."""
    # shortcut: advance widths only, no kerning; fine for these few words, use a shaper for more.
    s = size / UPM
    glyphs, pen_x = [], 0.0
    for ch in text:
        name = CMAP[ord(ch)]
        pen = SVGPathPen(GLYPHS)
        GLYPHS[name].draw(pen)
        glyphs.append((pen_x, pen.getCommands()))
        pen_x += GLYPHS[name].width + tracking * UPM
    width = (pen_x - tracking * UPM) * s
    left = {"start": x, "middle": x - width / 2, "end": x - width}[anchor]
    stroke = f' stroke="{fill}" stroke-width="{bold}" stroke-linejoin="round"' if bold else ""
    paths = "".join(f'<path transform="translate({gx:.1f} 0)" d="{d}"/>' for gx, d in glyphs if d)
    return (f'<g transform="translate({left:.2f} {baseline:.2f}) scale({s:.5f} {-s:.5f})" '
            f'fill="{fill}"{stroke}>{paths}</g>')


def rune_b(cx: float, cy: float, height: float, fill: str, bold: float) -> str:
    """The ᛒ, its ink box centred on (cx, cy) and `height` tall."""
    name = CMAP[ord("ᛒ")]
    pen, box = SVGPathPen(GLYPHS), BoundsPen(GLYPHS)
    GLYPHS[name].draw(pen)
    GLYPHS[name].draw(box)
    x0, y0, x1, y1 = box.bounds
    s = height / (y1 - y0)
    tx, ty = cx - (x0 + x1) / 2 * s, cy + (y0 + y1) / 2 * s
    return (f'<path transform="translate({tx:.2f} {ty:.2f}) scale({s:.5f} {-s:.5f})" fill="{fill}" '
            f'stroke="{fill}" stroke-width="{bold}" stroke-linejoin="round" d="{pen.getCommands()}"/>')


def svg(width: int, height: int, body: str, label: str) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}" role="img" aria-label="{label}">\n{NOTICE}\n{body}\n</svg>\n')


def icon() -> dict[str, str]:
    # 512 units square. The rune is thickened so its stems survive at 16 px.
    plain = f'<circle cx="256" cy="256" r="256" fill="{RACING}"/>' + rune_b(256, 256, 300, GOLD, 24)
    return {"icon": svg(512, 512, plain, "Bragd")}


def wordmark() -> str:
    return svg(560, 160, line(RUNES, 150, 280, 132, RACING, tracking=0.12, bold=20), "ᛒᚱᛅᚴᚦ")


def splash() -> str:
    body = (
        '<defs><radialGradient id="splash-glow" cx="0.5" cy="0.42" r="0.75">'
        f'<stop offset="0" stop-color="{MID}"/><stop offset="0.55" stop-color="{RACING}"/>'
        f'<stop offset="1" stop-color="{DEEPEST}"/></radialGradient></defs>'
        '<rect width="960" height="540" fill="url(#splash-glow)"/>'
        + line(RUNES, 150, 480, 250, GOLD, tracking=0.12, bold=14)
        + f'<rect x="400" y="292" width="160" height="3" fill="{LIGHT}"/>'
        + line("Bragd", 64, 480, 380, PALE, bold=10)
        + line("bragð — a clever move", 30, 480, 432, PALE)
    )
    return svg(960, 540, body, "Bragd ᛒᚱᛅᚴᚦ: bragð — a clever move")


def render(svg_path: pathlib.Path, size: int) -> bytes:
    """PNG bytes, `size` px wide."""
    return subprocess.run(["rsvg-convert", "-w", str(size), str(svg_path)],
                          check=True, capture_output=True).stdout


def main() -> None:
    if not shutil.which("rsvg-convert"):
        raise SystemExit("needs rsvg-convert (librsvg)")
    art = {**icon(), "wordmark-runes": wordmark(), "splash": splash()}
    (BRAND / "png").mkdir(parents=True, exist_ok=True)
    for name, text in art.items():
        path = BRAND / f"{name}.svg"
        path.write_text(text)
        # A wide picture at 16 px wide is a smudge; the icons are what must work small.
        for size in (16, 32, 256, 1024) if name.startswith("icon") else (256, 1024):
            (BRAND / "png" / f"{name}-{size}.png").write_bytes(render(path, size))

    icons = BRAND / "icons"
    icons.mkdir(exist_ok=True)
    source = BRAND / f"{APP_ICON}.svg"
    for file, size in (("32x32.png", 32), ("128x128.png", 128), ("128x128@2x.png", 256), ("icon.png", 512)):
        (icons / file).write_bytes(render(source, size))
    # Each size rendered from the vector, not shrunk from the largest bitmap.
    sized = {n: Image.open(io.BytesIO(render(source, n))).convert("RGBA")
             for n in (16, 24, 32, 48, 64, 128, 256, 512, 1024)}
    ico = [sized[n] for n in (16, 24, 32, 48, 64, 128, 256)]
    ico[-1].save(icons / "icon.ico", sizes=[i.size for i in ico], append_images=ico[:-1])
    icns = [sized[n] for n in (16, 32, 64, 128, 256, 512, 1024)]
    icns[-1].save(icons / "icon.icns", append_images=icns[:-1])
    print(f"wrote {len(art)} pictures, their PNGs and the icon set from {APP_ICON}")


if __name__ == "__main__":
    main()
